# Payload builders and parsers
# ---------------------------------------------------------------------------


def drive_payload(linear_mm_s: int, angular_mrad_s: int, lateral_mm_s: int = 0) -> bytes:
    """Build a Drive payload.

    Angular velocity is milliradians per second — see the note in Types.h:
    millidegrees in an int16 would cap the robot at 32.7 deg/s.
    """
    return struct.pack("<hhh", int(linear_mm_s), int(angular_mrad_s), int(lateral_mm_s))


def drive_raw_payload(left_per_mil: int, right_per_mil: int) -> bytes:
    return struct.pack("<hh", int(left_per_mil), int(right_per_mil))


def set_stream_payload(rate_hz: int, enabled_mask: int = 0xFFFFFFFF) -> bytes:
    return struct.pack("<HI", int(rate_hz), int(enabled_mask) & 0xFFFFFFFF)


def set_aux_payload(channel: int, value: int) -> bytes:
    return struct.pack("<Bh", int(channel) & 0xFF, int(value))


@dataclass
class HelloAck:
    protocol_version: int
    sensor_count: int
    holonomic: bool
    max_linear_mm_s: int
    max_angular_mrad_s: int
    command_timeout_ms: int
    board: str

    @classmethod
    def parse(cls, payload: bytes) -> HelloAck:
        if len(payload) < 9:
            raise ProtocolError("short HelloAck")
        version, count, holonomic = payload[0], payload[1], payload[2]
        max_linear, max_angular, timeout = struct.unpack("<HHH", payload[3:9])
        board = payload[9:].split(b"\x00", 1)[0].decode("ascii", "replace")
        return cls(version, count, bool(holonomic), max_linear, max_angular, timeout, board)


@dataclass
class SensorDescriptor:
    id: int
    kind: SensorKind
    unit: Unit
    channels: int
    scale_exp: int
    rate_hz: int
    failed: bool
    name: str

    @property
    def scale(self) -> float:
        """Multiply a raw integer value by this to get the physical value."""
        return 10.0**self.scale_exp

    def to_physical(self, raw: int) -> float:
        return raw * self.scale

    @classmethod
    def parse(cls, payload: bytes) -> SensorDescriptor:
        if len(payload) < 8:
            raise ProtocolError("short Descriptor")
        sensor_id, kind, unit, channels = payload[0], payload[1], payload[2], payload[3]
        scale_exp = struct.unpack("<b", payload[4:5])[0]
        (rate_hz,) = struct.unpack("<H", payload[5:7])
        failed = bool(payload[7])
        name = payload[8:].split(b"\x00", 1)[0].decode("ascii", "replace")
        return cls(
            id=sensor_id,
            kind=SensorKind(kind) if kind in SensorKind._value2member_map_ else SensorKind.CUSTOM,
            unit=Unit(unit) if unit in Unit._value2member_map_ else Unit.NONE,
            channels=channels,
            scale_exp=scale_exp,
            rate_hz=rate_hz,
            failed=failed,
            name=name,
        )


@dataclass
class Sample:
    sensor_id: int
    timestamp_ms: int
    values: list[int] = field(default_factory=list)

    @classmethod
    def parse(cls, payload: bytes) -> Sample:
        if len(payload) < 6:
            raise ProtocolError("short Sample")
        sensor_id = payload[0]
        (timestamp_ms,) = struct.unpack("<I", payload[1:5])
        channels = payload[5]
        expected = 6 + channels * 4
        if len(payload) < expected:
            raise ProtocolError("Sample truncated")
        values = list(struct.unpack(f"<{channels}i", payload[6:expected]))
        return cls(sensor_id=sensor_id, timestamp_ms=timestamp_ms, values=values)


@dataclass
class Status:
    state: NodeState
    estop: bool
    battery_mv: int
    uptime_ms: int
    dropped_frames: int

    @classmethod
    def parse(cls, payload: bytes) -> Status:
        if len(payload) < 10:
            raise ProtocolError("short Status")
        state = payload[0]
        estop = bool(payload[1])
        battery_mv, uptime_ms, dropped = struct.unpack("<HIH", payload[2:10])
        return cls(
            state=NodeState(state) if state in NodeState._value2member_map_ else NodeState.FAULT,
            estop=estop,
            battery_mv=battery_mv,
            uptime_ms=uptime_ms,
            dropped_frames=dropped,
        )


@dataclass
class Ack:
    of_type: int
    code: AckCode

    @property
    def ok(self) -> bool:
        return self.code is AckCode.OK

    @classmethod
    def parse(cls, payload: bytes) -> Ack:
        if len(payload) < 2:
            raise ProtocolError("short Ack")
        code = payload[1]
        return cls(
            of_type=payload[0],
            code=AckCode(code) if code in AckCode._value2member_map_ else AckCode.REJECTED,
        )


@dataclass
class LogMessage:
    level: LogLevel
    text: str

    @classmethod
    def parse(cls, payload: bytes) -> LogMessage:
        if not payload:
            raise ProtocolError("short Log")
        level = payload[0]
        return cls(
            level=LogLevel(level) if level in LogLevel._value2member_map_ else LogLevel.INFO,
            text=payload[1:].decode("ascii", "replace"),
        )
